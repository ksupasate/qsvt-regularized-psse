    anchor_unitarity = workload_value(
        "anchor_4x4_benchmark_alpha_d31", "dense_block_encoding_unitarity_error"
    )

    def resource_value(field: str) -> str | None:
        if resource is None:
            return None
        rows = resource[resource["field"] == field]
        return str(rows.iloc[0]["value"]) if len(rows) else None


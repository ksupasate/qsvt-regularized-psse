def _pooled_readout_range(readout: pd.DataFrame) -> str:
    pooled = readout[readout["observable_label"] == "__all_signed_pooled__"]
    if pooled.empty:
        return "not available"
    low = pooled.loc[pooled["shots"].idxmin()]
    high = pooled.loc[pooled["shots"].idxmax()]
    return (
        f"pooled mean relative {low['mean_relative_error_vs_ridge']:.3e} at "
        f"{int(low['shots'])} shots to {high['mean_relative_error_vs_ridge']:.3e} at "
        f"{int(high['shots'])} shots"
    )


def _tex_escape(text: str) -> str:
    out = text.replace("{", r"\{").replace("}", r"\}")
    for char, repl in [
        ("&", r"\&"),
        ("%", r"\%"),
        ("_", r"\_"),
        ("#", r"\#"),
        ("^", "\\textasciicircum{}"),
        ("~", "\\textasciitilde{}"),
    ]:
        out = out.replace(char, repl)
    return out


def _write_tex(frame: pd.DataFrame, path: Path) -> None:
    lines = [
        r"% Source: outputs/qsvt_error_budget/error_budget.csv",
        r"% Regenerate: .venv/bin/python scripts/build_qsvt_error_budget_table.py",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Combined component error budget for the selected-submatrix QSVT workload. "
        r"Every value is taken from a generated repository artifact; components without a "
        r"compiled realization are labeled modeled or excluded. This table is an accounting "
        r"boundary, not a closed end-to-end error theorem.}",
        r"\label{tab:error_budget}",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{p{0.16\textwidth}p{0.05\textwidth}p{0.13\textwidth}p{0.12\textwidth}"
        r"p{0.28\textwidth}p{0.14\textwidth}}",
        r"\hline",
        r"Component & Symbol & Scale & Status & Value or range & Limitation \\",
        r"\hline",
    ]
    for _, row in frame.iterrows():
        cells = [
            _tex_escape(str(row["component"])),
            str(row["symbol"]),
            _tex_escape(str(row["scale"])),
            _tex_escape(str(row["measured_modeled_or_excluded"])),
            _tex_escape(str(row["value_or_range"])),
            _tex_escape(str(row["limitation"])),
        ]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table*}", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def _to_markdown(frame: pd.DataFrame) -> str:
    headers = [str(c) for c in frame.columns]
    rows = [[str(v) for v in row] for row in frame.itertuples(index=False)]
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(cell.replace("|", "/") for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    frame = pd.DataFrame(build_rows(), columns=COLUMNS)
    frame.to_csv(OUTPUT_DIR / "error_budget.csv", index=False)
    _write_tex(frame, OUTPUT_DIR / "error_budget.tex")
    md_lines = [
        "# Combined QSVT Selected-Output Error Budget (Goal C)",
        "",
        "Accounting boundary for the component errors of the selected-output workload; "
        "not a closed end-to-end error theorem. Values come only from generated artifacts.",
        "",
        _to_markdown(frame),
        "",
    ]
    (OUTPUT_DIR / "error_budget.md").write_text("\n".join(md_lines), encoding="utf-8")
    manifest = {
        "artifact_name": "qsvt_error_budget",
        "sources": {
            "workload": str(WORKLOAD),
            "block_encoding_report": str(BE_REPORT),
            "state_preparation_report": str(STATE_PREP),
            "lookup_reconstruction": str(LOOKUP),
            "quantization_report": str(QUANT),
            "wrapper_demo": str(WRAPPER),
            "readout_statistics": str(READOUT),
            "fixed_case_resource_ledger": str(RESOURCE),
            "nonlinear_table": str(NONLINEAR_TABLE),
        },
        "regeneration_command": ".venv/bin/python scripts/build_qsvt_error_budget_table.py",
        "note": "accounting boundary, not a closed end-to-end error theorem",
    }
    (OUTPUT_DIR / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Error budget written to {OUTPUT_DIR} ({len(frame)} rows)")


if __name__ == "__main__":
    main()

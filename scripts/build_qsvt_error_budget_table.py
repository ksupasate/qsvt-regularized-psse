"""Goal C: combined component error-budget table for the selected-output workload.

Reads only values that were actually generated by repository experiments; missing
sources are recorded as ``not available`` with the expected file path. The table
is an accounting boundary, not a closed end-to-end error theorem.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

OUTPUT_DIR = Path("outputs/qsvt_error_budget")

WORKLOAD = Path("outputs/qsvt_selected_workload_extension/selected_workload_results.csv")
BE_REPORT = Path("outputs/ieee_qsvt_pipeline_boundary/block_encoding_report.csv")
STATE_PREP = Path("outputs/ieee_qsvt_pipeline_boundary/state_preparation_report.csv")
LOOKUP = Path(
    "outputs/tqe_revision_experiments/sparse_block_encoding_demo/reconstructed_block_error.csv"
)
QUANT = Path("outputs/sparse_quantization_error_report/quantization_error_report.csv")
WRAPPER = Path("outputs/sparse_block_encoding_wrapper_demo/wrapper_demo_results.csv")
READOUT = Path(
    "outputs/tqe_revision_experiments/readout_statistics/readout_shot_scaling_summary.csv"
)
RESOURCE = Path(
    "outputs/tqe_revision_experiments/end_to_end_resource_case/fixed_case_resource_ledger.csv"
)
NONLINEAR_TABLE = Path("manuscript/tables/nonlinear_convergence_revision.tex")

COLUMNS = [
    "component",
    "symbol",
    "source_table_or_script",
    "scale",
    "measured_modeled_or_excluded",
    "value_or_range",
    "included_in_current_resource_count",
    "limitation",
]


def _read(path: Path) -> pd.DataFrame | None:
    return pd.read_csv(path) if path.is_file() else None


def _fmt(value: float) -> str:
    return f"{value:.3e}"


def build_rows() -> list[dict[str, str]]:
    workload = _read(WORKLOAD)
    be_report = _read(BE_REPORT)
    state_prep = _read(STATE_PREP)
    lookup = _read(LOOKUP)
    quant = _read(QUANT)
    wrapper = _read(WRAPPER)
    readout = _read(READOUT)
    resource = _read(RESOURCE)

    def workload_value(workload_id: str, column: str) -> float | None:
        if workload is None:
            return None
        rows = workload[workload["workload_id"] == workload_id]
        return float(rows.iloc[0][column]) if len(rows) else None


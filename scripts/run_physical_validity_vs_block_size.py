#!/usr/bin/env python3
"""Run the benchmark-reference-validity vs block-size study and emit manuscript assets.

Purely classical full-support study (no circuits, no selector): nested outcome-independent
blocks per IEEE case, generated-benchmark-reference error under two declared alpha policies.

Outputs: outputs/physical_validity_vs_block_size/ (CSVs, provenance, manifest, checksums),
manuscript/tables/physical_validity_vs_block_size.tex,
manuscript/figures/fig_physical_validity_vs_block_size.pdf.
"""


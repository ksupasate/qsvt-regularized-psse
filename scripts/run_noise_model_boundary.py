"""Run the depolarizing noise-model boundary study (W2b, must-fix #3).

Simulates the identity-verified smallest executed circuit (IEEE-14 4x4, degree-31 anchor;
7 qubits; 60,587 frozen default-target gates) on the Aer density-matrix method under a uniform
depolarizing model (same p on every 1q rz/sx/x and 2q cx basis gate), with exact noisy
readout distributions plus genuine sampled Aer counts at fixed seeds.

Outputs: outputs/noise_model_boundary/ (CSVs, provenance, manifest, checksums),
manuscript/tables/noise_model_boundary.tex,
manuscript/figures/fig_noise_model_boundary.pdf.
"""

